import os, io
R = r"C:\Users\Administrator\Desktop\新书\火影忍者\七人赛马"
CMD = os.path.join(R, "资料", "指令", "正文轮")
os.makedirs(CMD, exist_ok=True)

PLAN = open(os.path.join(R, "_融合产物", "融合_总稿_章纲轮.md"), encoding="utf-8").read()

TPL = """【正文轮 · 第 1 批：18-A《桥下之鬼》】

你是「七人赛马」选手 **{me}**。写正文，只写 18-A 一章（3000-3500 字）。18-B、19 段后面分批再写。

## 硬指标
- 3000-3500 字；单段 ≤150 字；破折号 0
- "极其"≤1、"死死"≤2、"像"≤10
- 禁"不是A是B"句式、禁正能量总结句
- 每段带幕号（18-A-1、18-A-2...）

## 本章类型 = 解密章
- 只写信号不写剧透；层次释放
- 情绪刺激点 ≥2 处（恐惧／后怕／悚然，类型不重复）

## 红线
- 九尾不离体（查克拉协同）
- 卡多必须逃、不改 18 章
- 情绪值 +2（48→50）
- 月面只解部分谜团
- "桥那边有鬼"不在新章重提
- 转生眼残片不写"激活"
- 远处月面不弹【环境扫描】
- 零新增实体（黑石头／那根东西不命名）
- 白只用千本、不展冰遁
- 再不斩／白只制伏不取命（"留气儿不留命"）

## 接缝
- 开头两句：涟漪凝滞退回＋"它在确认我是不是看客"
- 不复述 18 章末的客观叙述
- 一级触发：18 章末涟漪推到半海凝滞退回
- 二级触发：阿松天刚黑透拍门求救（两个孩子前晚下桥墩捡木片，回来发高烧）

## 硬节拍
- 陆炎"没把握不动"：对海图、叫再不斩白、等退潮
- 桥头汇合后无声放倒两名暗哨（刀背击晕＋千本钉关节，不取命）
- 陆炎内心吐槽："不愧是鬼人再不斩。还好当初是去跟他谈合同，想想就后怕——那时候我居然敢当面坐下来跟他谈价钱。"（后怕口吻，不是赞颂）
- "鬼"现形：浸染潜水工，皮囊发白、动作慢得不像活人
- 九尾被抽走一丝 → 精神空间应激翻涌 → 陆炎上撤压住（13 章疏导法＋五险一金话术）
- 章末钩：卡多亲自靠岸、手按石柱、雾倒卷

## 输出
写到：{root}\\{me}\\产出\\正文轮\\18-A_桥下之鬼.md
写完回：「{me} 18-A 正文已落盘」

## 章纲定稿全文（唯一蓝本）

{plan}
"""

for me in ["Qianwen", "Doubao"]:
    txt = TPL.format(me=me, root=R, plan=PLAN)
    fp = os.path.join(CMD, me + ".txt")
    io.open(fp, "w", encoding="utf-8").write(txt)
    print(f"OK {me}.txt  ({os.path.getsize(fp)//1024} KB)")

print(f"\n位置: {CMD}")
