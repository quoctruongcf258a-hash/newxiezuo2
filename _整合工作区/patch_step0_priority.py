# patch_step0_priority.py — 给步骤0提示词加「冲突处理原则」
from pathlib import Path

T = Path(r"F:\赛马23环整合工作室\程序2改装版\prompts\00_初始化\故事梗概.md")
text = T.read_text(encoding="utf-8")

# 找到「第一步：读懂用户想要的感觉」段落，在后面加一条
OLD = '''- 哪些标签互相冲突，需要取舍或分层

### 第二步：产出 1 份文件'''

NEW = '''- 哪些标签互相冲突，需要取舍或分层

### 冲突处理原则（重要）

遇到互相矛盾的关键词时，**不要为了兼容而扭曲故事**。按下面优先级排序：

1. **核心项**（题材、细分、章节数、主角性别）：硬约束，必须保留
2. **主线项**（金手指、核心冲突、感情主线）：优先保留，可微调
3. **支线项**（配角性格、次要标签）：可以降级为支线或前史
4. **冲突项**：**该舍就舍**，直接砍掉，不要硬融

**判定标准**：
- 两个关键词放在一起，故事变拧巴了 → **舍一个**
- 某个关键词导致主线不成立 → **舍它**
- 某个关键词只能作为彩蛋存在 → **降级为支线**
- 宁可少用一个标签，也不要让主线扭曲

**举例**：
- 「无 CP」+「双向暗恋」→ 冲突，舍「双向暗恋」
- 「无敌流」+「缓慢成长」→ 冲突，舍「缓慢成长」
- 「女强」+「小白花」→ 冲突，舍「小白花」

### 第二步：产出 1 份文件'''

if "冲突处理原则（重要）" in text:
    print("已改过")
elif OLD not in text:
    print("✗ 找不到锚点")
    i = text.find("哪些标签互相冲突")
    if i >= 0:
        print(repr(text[i-100:i+300]))
else:
    text = text.replace(OLD, NEW, 1)
    T.write_text(text, encoding="utf-8")
    print("✔ 已加冲突处理原则")