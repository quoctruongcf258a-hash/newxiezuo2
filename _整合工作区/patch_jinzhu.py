from pathlib import Path

T = Path(r"F:\赛马23环整合工作室\程序2改装版\prompts\00_初始化\故事梗概.md")
text = T.read_text(encoding="utf-8")

OLD = '''### 第二步：产出 1 份文件'''

NEW = '''### 金手指处理原则（重要）

**金手指不能太多，也不能一次性全给**。按下面规则处理：

1. **数量控制**：从用户给的候选中，只保留 **1~2 个最关键**的作为「核心金手指」，其余作为「可升级分支」或「后期解锁」

2. **分层释放**：
   - **开局**：只给 1 个（最多 2 个）最基础的能力，让读者看到「不一样」
   - **前期**：逐步解锁 1 个衍生能力或升级形态
   - **中期**：再开放 1 个新方向或隐藏用法
   - **后期/终局**：最终形态或底牌

3. **可以升级、后续补充**：
   - 核心金手指要有「成长路径」（初级→中级→高级→终极）
   - 不要在梗概里就把所有形态列完
   - 留「意外解锁」的空间给后续环节发挥

4. **不能一次性全给**：
   - 用户给的候选里有 3 个金手指 → 只选 1~2 个当核心，剩下的降级为「支线能力」或「不用」
   - 一次给太多 → 读者记不住，也失去追读期待
   - 宁可少给，慢慢加

**判定标准**：
- 开局只给主角 **1 个**「这本书独有」的能力 → 读者记住这本
- 后续升级/解锁 → 每次都给读者一个「爽点」
- 一次性给 5 个金手指 → 全部沦为背景板

### 第二步：产出 1 份文件'''

if "金手指处理原则（重要）" in text:
    print("已改过")
elif OLD not in text:
    print("✗ 找不到锚点")
    i = text.find("第二步：产出 1 份文件")
    if i >= 0:
        print(repr(text[i-200:i+200]))
else:
    text = text.replace(OLD, NEW, 1)
    T.write_text(text, encoding="utf-8")
    print("✔ 已加金手指原则")