def 选池(频道: str, 题材: str, 细分: str = "") -> dict:
    """按 频道_题材 / 频道_细分 / 通用 依次查找名字池。"""
    keys = [
        f"{频道}_{细分}",
        f"{频道}_{题材}",
        f"{频道}_通用",
        "通用",
    ]
    for k in keys:
        if k in NAME_POOLS:
            return NAME_POOLS[k]
    return NAME_POOLS["通用"]


def 补人物列表(json_path: Path, 覆盖: bool = False):
    data = json.loads(json_path.read_text(encoding="utf-8"))

    if data.get("人物设计列表") and not 覆盖:
        print(f"已有 人物设计列表：{data['人物设计列表']}")
        print("如需重新生成，加 --force")
        return

    频道 = data.get("频道", "")
    题材 = data.get("题材", "")
    细分 = data.get("细分", "")
    主角性别 = data.get("主角性别", "")
    配角数 = int(data.get("配角数量") or 0)

    pool = 选池(频道, 题材, 细分)
    女主池 = list(pool["女主"])
    配角池 = list(pool["配角"])
    random.shuffle(女主池)
    random.shuffle(配角池)

    # 主角
    主角名 = 女主池[0]
    已用 = {主角名}

    # 配角：从配角池抽，不够就从女主池补，都不够就加数字后缀
    配角名 = []
    for name in 配角池:
        if len(配角名) >= 配角数:
            break
        if name not in 已用:
            配角名.append(name)
            已用.add(name)
    for name in 女主池[1:]:
        if len(配角名) >= 配角数:
            break
        if name not in 已用:
            配角名.append(name)
            已用.add(name)
    i = 1
    while len(配角名) < 配角数:
        name = f"{配角池[i % len(配角池)]}{i // len(配角池) + 1}"
        if name not in 已用:
            配角名.append(name)
            已用.add(name)
        i += 1

    lst = [主角名] + 配角名
    data["人物设计列表"] = lst

    json_path.write_text(
        json.dumps(data, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )

    print(f"✔ 已写入 人物设计列表（{len(lst)} 人）：{lst}")
    print(f"  主角：{主角名}")
    print(f"  配角（{len(配角名)}）：{', '.join(配角名)}")
    print(f"  → {json_path}")


